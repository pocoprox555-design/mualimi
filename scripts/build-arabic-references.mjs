function stripLines(content) {
  return cleanArabicText(String(content || '')
    .replace(/\[ص\s*\d+\s*-\s*س\s*\d+\]/g, '')
    .replace(/[\u061c\u200e\u200f\u202a-\u202e\u2066-\u2069]/g, ''))
}

function pageRole(section, text, first, last) {
  if (section.kind === 'index') return { kind: 'index', label: 'الفهرس الرسمي ونطاقات الدروس' }
  if (section.kind === 'dictionary') return { kind: 'definitions', label: 'تعريف ألفاظ معجم الطالب واستعمالاتها' }
  if (/أسئلة|المناقشة|ناقش|تمرينات|التطبيقات|حلل|استخرج|أعرب/i.test(text)) return { kind: 'questions', label: 'أسئلة وتطبيقات وتقويم للدرس' }
  if (/معاني الكلمات|معاني المفردات|المفردات|إضاءة/i.test(text)) return { kind: 'definitions', label: 'مفردات وتمهيد وتعريفات مساعدة' }
  if (/إعراب|اإلعراب|القاعدة|األحكام|األمثلة|الجمل اآلتية/i.test(text) && section.kind === 'grammar') return { kind: 'grammar_examples', label: 'شرح نحوي مع أمثلة وإعراب وتطبيق' }
  if (/التعليق النقدي|التحليل النقدي|خصائص|سيرة|حياته|نشأته/i.test(text) && ['literature', 'criticism'].includes(section.kind)) return { kind: 'literary_analysis', label: 'سيرة وخصائص وتحليل أدبي أو نقدي' }
  if (first) return { kind: `${section.kind}_start`, label: 'بداية الدرس وتمهيده ومفاهيمه الأساسية' }
  if (last) return { kind: `${section.kind}_end`, label: 'استكمال الدرس وخلاصته أو تقويمه الختامي' }
  return { kind: `${section.kind}_content`, label: 'استكمال منظم لمادة الدرس وأفكاره وأمثلته' }
}

for (const config of books) {
  const manifest = await readManifest(config.bookId)
  if (!manifest) throw new Error(`Missing imported book ${config.bookId}`)
  if (manifest.pageCount !== config.pageCount) throw new Error(`Page count mismatch for ${config.bookId}`)
  const sectionFor = (pageNumber) => config.sections.find((section) => pageNumber >= section[3] && pageNumber <= section[4])
  const pages = []
  for (const sourcePage of manifest.pages) {
    const section = sectionFor(sourcePage.pageNumber)
    if (!section) throw new Error(`No official section for ${config.bookId} page ${sourcePage.pageNumber}`)
    const opened = await openPage(config.bookId, sourcePage.pageNumber)
    const text = stripLines(opened.content)
    const first = sourcePage.pageNumber === section[3]
    const last = sourcePage.pageNumber === section[4]
    const role = pageRole({ kind: section[2] }, text, first, last)
    const position = section[4] === section[3] ? 'صفحة مستقلة' : `الصفحة ${sourcePage.pageNumber - section[3] + 1} من ${section[4] - section[3] + 1} في هذا الدرس`
    pages.push({
      pageNumber: sourcePage.pageNumber,
      title: first ? section[1] : `${section[1]} — ${role.label}`,
      summary: `${section[5]} ${position}، ووظيفتها: ${role.label}. افتح النص الكامل عند الحاجة إلى الأمثلة أو الشواهد أو الإعراب الدقيق.`,
      kind: role.kind,
      unit: section[0],
      section: section[1],
      lessonRange: { from: section[3], to: section[4] },
      continuesFrom: first ? null : sourcePage.pageNumber - 1,
      continuesTo: last ? null : sourcePage.pageNumber + 1,
      needsOcr: false,
      lineRange: sourcePage.lineRange,
      notes: null,
    })
  }

  const review = {
    schemaVersion: 1,
    bookId: config.bookId,
    metadata: {
      title: manifest.title,
      subject: 'اللغة العربية',
      grade: 'السادس الإعدادي',
      branch: 'عام',
      part: config.part,
      edition: 'الطبعة الرابعة',
      year: 2025,
      hijriYear: 1447,
      publisher: 'جمهورية العراق — وزارة التربية — المديرية العامة للمناهج',
    },
    verification: {
      metadataSourcePages: [1],
      structureSourcePage: config.indexPage,
      pageCount: pages.length,
      readablePages: pages.length,
      needsOcrPages: 0,
      reviewMethod: `مراجعة النص المرقم وربط كل صفحة بالفهرس الرسمي في الصفحة ${config.indexPage}.`,
    },
    sections: config.sections.map(([unit, lesson, kind, from, to, overview]) => ({ unit, lesson, kind, from, to, overview })),
    quality: {
      strengths: ['كل الصفحات تحتوي نصًا قابلًا للقراءة', 'فهرس رسمي مفصل', 'دمج المطالعة والقواعد والتعبير والأدب والنقد'],
      concerns: ['تشوهات OCR متفرقة في ترتيب الحروف والتشكيل', 'بعض الصفحات كثيفة الأعمدة والجداول'],
      policy: 'استخدم خريطة الدروس أولًا ثم افتح الصفحة كاملة للتحقق من الأمثلة والإعراب والنصوص.',
    },
  }

  await mkdir(outputDir, { recursive: true })
  await writeFile(path.join(outputDir, `${config.bookId}.review.json`), `${JSON.stringify(review, null, 2)}\n`, 'utf8')
  await writeFile(path.join(outputDir, `${config.bookId}.pages.json`), `${JSON.stringify({ schemaVersion: 1, bookId: config.bookId, pages }, null, 2)}\n`, 'utf8')
  console.log(JSON.stringify({ bookId: config.bookId, pages: pages.length, sections: config.sections.length }))
}
